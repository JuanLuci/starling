def smooth(points, n=4):
    """Catmull-Rom through the points, n steps a segment."""
    if len(points) < 3:
        return points
    out = []
    pts = [points[0]] + points + [points[-1]]
    for i in range(1, len(pts) - 2):
        p0, p1, p2, p3 = pts[i - 1], pts[i], pts[i + 1], pts[i + 2]
        for k in range(n):
            t = k / n
            t2, t3 = t * t, t * t * t
            out.append(tuple(
                0.5 * ((2 * p1[j]) + (-p0[j] + p2[j]) * t + (2 * p0[j] - 5 * p1[j] + 4 * p2[j] - p3[j]) * t2
                       + (-p0[j] + 3 * p1[j] - 3 * p2[j] + p3[j]) * t3)
                for j in range(2)))
    out.append(points[-1])
    return out


def densify(points, step=0.12):
    """Points no farther apart than `step` (em), so a straight stroke can wobble too."""
    out = [points[0]]
    for a, b in zip(points, points[1:]):
        n = max(1, int(math.dist(a, b) / step))
        for k in range(1, n + 1):
            out.append((a[0] + (b[0] - a[0]) * k / n, a[1] + (b[1] - a[1]) * k / n))
    return out


def write(draw, text, x, y, size, ink=(60, 60, 64), seed=0, width=None, wobble=1.0, slant=(7.0, 3.5)):
    """Write `text` with its baseline at (x, y), `size` px to the em; returns the end x."""
    rnd = random.Random(seed)
    width = width or max(1.4, size * 0.07)
    pen_x = x
    drift = 0.0
    for ch in text:
        glyph = G.get(ch) or G.get(ch.lower()) or G["?"]
        advance, strokes = glyph
        # This letter's own way of being written.
        lean = math.radians(rnd.gauss(*slant))
        scale = size * rnd.gauss(1.0, 0.05)
        drift += rnd.gauss(0, 0.012) * size
        drift *= 0.85
        base = y + drift
        for stroke in strokes:
            pts = densify(stroke)
            j = 0.028 * wobble
            pts = [(px + rnd.gauss(0, j), py + rnd.gauss(0, j)) for px, py in pts]
            # Overshoot or stop short at the ends, as a pen does.
            if len(pts) >= 2:
                for end, prev in ((0, 1), (-1, -2)):
                    a, b = pts[end], pts[prev]
                    k = rnd.uniform(-0.04, 0.09)
                    pts[end] = (a[0] + (a[0] - b[0]) * k * 3, a[1] + (a[1] - b[1]) * k * 3)
            pts = smooth(pts)
            screen = [
                (pen_x + (px + py * math.tan(lean)) * scale, base - py * scale)
                for px, py in pts
            ]
            if len(screen) == 1:
                screen = screen * 2
            w = width * rnd.uniform(0.85, 1.15)
            draw.line(screen, fill=ink, width=max(1, round(w)), joint="curve")
            r = w / 2
            for px, py in (screen[0], screen[-1]):
                draw.ellipse([px - r, py - r, px + r, py + r], fill=ink)
        pen_x += (advance + 0.09 + rnd.gauss(0, 0.025)) * scale
    return pen_x


def measure(text, size):
    return sum((G.get(c) or G.get(c.lower()) or G["?"])[0] + 0.09 for c in text) * size
